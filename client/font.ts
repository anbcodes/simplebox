export type Glyph = { rows: string[]; w: number };

function parse(table: Record<string, string>): Map<string, Glyph> {
  const out = new Map<string, Glyph>();
  for (const [ch, art] of Object.entries(table)) {
    const rows = art.split(" ").map((r) => (r === "-" ? "" : r));
    out.set(ch, { rows, w: Math.max(...rows.map((r) => r.length)) });
  }
  return out;
}

function embolden(font: Map<string, Glyph>): Map<string, Glyph> {
  const out = new Map<string, Glyph>();
  for (const [ch, g] of font) {
    const rows = g.rows.map((r) => {
      if (!r.includes("#")) return r;
      let b = "";
      for (let i = 0; i <= g.w; i++) b += r[i] === "#" || r[i - 1] === "#" ? "#" : ".";
      return b;
    });
    out.set(ch, { rows, w: g.w + 1 });
  }
  return out;
}

const ui = parse(UI);
export const glyphs: Record<Font, Map<string, Glyph>> = { ui, bold: embolden(ui), mono: parse(MONO) };

export function glyph(ch: string, font: Font = "ui"): Glyph {
  const g = glyphs[font];
  return g.get(ch) ?? (ch === "\t" ? g.get(" ")! : g.get("\u0000")!);
}

/** How far the pen moves after a character. */
export function advance(ch: string, font: Font = "ui"): number {
  return font === "mono" ? MONO_W : glyph(ch, font).w + 1;
}

/** Width of a line of text in pixels. */
export function measure(text: string, font: Font = "ui"): number {
  if (font === "mono") return text.length * MONO_W;
  let w = 0;
  for (const ch of text) w += advance(ch, font);
  return Math.max(0, w - 1);
}

/** The index of the character under pixel offset x in a line (text.length past the end). */
export function charAt(text: string, x: number, font: Font = "ui"): number {
  let pos = 0;
  for (let i = 0; i < text.length; i++) {
    pos += advance(text[i]!, font);
    if (x < pos) return i;
  }
  return text.length;
}

/** The character index closest to pixel offset x in a line. */
export function indexAt(text: string, x: number, font: Font = "ui"): number {
  let pos = 0;
  for (let i = 0; i < text.length; i++) {
    const a = advance(text[i]!, font);
    if (x < pos + a / 2) return i;
    pos += a;
  }
  return text.length;
}
